#!/usr/bin/env node
/*
 * Generate the Caddy config that puts the alerts app behind HTTPS.
 *
 *   node scripts/make-caddyfile.js trade-desk.duckdns.org > deploy/Caddyfile
 *
 * WHY ONLY THE ALERTS APP, AND NOT EVERYTHING.
 *
 * Two facts decide this, and neither is a preference.
 *
 * First, a browser refuses a fetch from an https page to an http address. The
 * landing page probes all nine tools by fetching `${protocol}//${host}:${port}
 * /health` — cross-origin, by design. Serve that page over https while the
 * tools are still http and every fetch is blocked as mixed content: nine cards
 * that all say OFFLINE while nine healthy tools sit behind them. Worse than
 * where we started, because it looks like the tools broke.
 *
 * The alerts page has no such problem. Every fetch it makes is same-origin —
 * /api/alerts/*, /api/tools — so on https they are https. Its outbound links to
 * a card or to TradingView are NAVIGATIONS, which browsers allow to leave a
 * secure page. So it can move alone, today, and nothing degrades.
 *
 * Second, Caddy and the app cannot both hold a port. Serving every tool over
 * TLS means Caddy takes the public ports and the apps move to internal ones —
 * a coordinated change to deploy-tools.sh, to the tools registry, and to the qp
 * chart tool, which builds its screener source URLs from the same registry.
 * That is a migration, not a config file, and it should be done where it can be
 * watched rather than blind.
 *
 * So: the alerts app on 443, which is the one that NEEDS a secure origin —
 * Notification.requestPermission() is refused outright without one, which is
 * exactly what the browser reported. The rest keeps working unchanged on http.
 *
 * PORT 80 IS NOT OPTIONAL even though nothing is served there. Caddy proves it
 * controls the domain over port 80 before a certificate is issued, and again on
 * every renewal. It also bounces bare http:// to https, so a typed address
 * still lands somewhere.
 */

const fs = require('fs');
const path = require('path');

const domain = (process.argv[2] || '').trim().replace(/^https?:\/\//, '').replace(/\/$/, '');
if (!domain || !domain.includes('.')) {
  console.error('Usage: node scripts/make-caddyfile.js <your-domain>');
  console.error('   eg: node scripts/make-caddyfile.js trade-desk.duckdns.org');
  process.exit(1);
}

const reg = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'tools.config.json'), 'utf8'));
const alerts = (reg.apps || []).find(a => a.id === 'ALERTS');
if (!alerts) {
  console.error('No ALERTS app in tools.config.json — nothing to serve.');
  process.exit(1);
}

process.stdout.write(`# Generated by scripts/make-caddyfile.js — do not edit by hand.
# Regenerate after changing ports:
#   node scripts/make-caddyfile.js ${domain} > deploy/Caddyfile && sudo systemctl reload caddy

{
	# A real address gets expiry warnings from Let's Encrypt. Without one the
	# certificates still work; you are simply not told when a renewal starts
	# failing, and the first symptom is the site going down 90 days later.
	# email you@example.com
}

# The alerts app, over https on the standard port — so the address is just
# https://${domain} with no port to type.
#
# It is here and the screeners are not because this is the page that needs a
# secure origin: browsers refuse Notification.requestPermission() without one.
# The screeners stay on http until their ports are migrated; moving them alone
# would block the landing page's cross-origin health probes as mixed content.
${domain} {
	reverse_proxy 127.0.0.1:${alerts.port} {
		# Caddy terminates TLS and forwards plain http on the loopback, so the
		# app sees an http request from 127.0.0.1. Nothing reads this today,
		# but a proxy that hides the real scheme is the classic cause of a
		# redirect loop, so it is passed anyway.
		header_up X-Forwarded-Proto https
	}
	log {
		output file /var/log/caddy/alerts.log
	}
}
`);
